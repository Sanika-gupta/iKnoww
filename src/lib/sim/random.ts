/**
 * Deterministic pseudo-randomness.
 *
 * Every boot, every clone and every test run must produce identical history.
 * Without that, the beta convergence test would be flaky and a judge running the
 * app would see something different from the demo.
 */

/** mulberry32: small, fast, good enough for simulated market noise. */
export function makeRng(seed: number): () => number {
  let a = seed >>> 0;
  return function next(): number {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Standard normal via Box-Muller. Returns one draw per call. */
export function makeNormal(rng: () => number): () => number {
  let spare: number | null = null;
  return function normal(): number {
    if (spare !== null) {
      const v = spare;
      spare = null;
      return v;
    }
    let u = 0;
    let v = 0;
    let s = 0;
    do {
      u = rng() * 2 - 1;
      v = rng() * 2 - 1;
      s = u * u + v * v;
    } while (s >= 1 || s === 0);
    const mul = Math.sqrt((-2 * Math.log(s)) / s);
    spare = v * mul;
    return u * mul;
  };
}
